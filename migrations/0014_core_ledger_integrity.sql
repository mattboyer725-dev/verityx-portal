-- Core ledger integrity across server instances.
--
-- 1. A table that ever holds two events chaining from the same predecessor
--    (two genesis entries, or two children of one tip) is forked. Its rows are
--    MOVED, not deleted, to core_events_fork_archive with the reason, so the
--    evidence is kept; the live table restarts from a single genesis.
-- 2. seq gives a stable insertion order (timestamps tie within a millisecond).
-- 3. unique(prev_hash) makes a fork impossible at the database: whatever the
--    application does, a second child of one tip is rejected.

create table if not exists core_events_fork_archive (
  event_id text not null,
  event_type text not null,
  payload text not null,
  actor text not null,
  timestamp double precision not null,
  prev_hash text not null,
  signature text not null,
  hash text not null,
  archived_at timestamptz not null default now(),
  reason text not null
);
alter table core_events_fork_archive enable row level security;

do $$
begin
  if exists (select prev_hash from core_events group by prev_hash having count(*) > 1) then
    insert into core_events_fork_archive (event_id, event_type, payload, actor, timestamp, prev_hash, signature, hash, reason)
      select event_id, event_type, payload, actor, timestamp, prev_hash, signature, hash,
             'forked chain: more than one event shared a predecessor (multi-instance race before migration 0014)'
      from core_events;
    delete from core_events;
  end if;
end $$;

alter table core_events add column if not exists seq bigint generated by default as identity;
create unique index if not exists core_events_seq_key on core_events (seq);
create unique index if not exists core_events_prev_hash_key on core_events (prev_hash);
create unique index if not exists core_events_hash_key on core_events (hash);
